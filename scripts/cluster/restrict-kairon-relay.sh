#!/usr/bin/env bash
# Restrict the kairon-node console relay port to this host and in-cluster clients, and keep that
# across reboots with a oneshot systemd unit. Run on the Kairon node as root (or with sudo).
#
# The relay carries guest exec, files, console and the TCP tunnel behind one bearer token, so it
# must not be reachable from the internet. Veyron's pod reaches it at the node's own IP from a
# Cilium pod address, so the node itself and the pod range stay allowed.
#
#   sudo scripts/cluster/restrict-kairon-relay.sh                # port 22230, pods 10.0.0.0/8
#   sudo scripts/cluster/restrict-kairon-relay.sh --port 8090 --allow 10.42.0.0/16 --allow 192.0.2.7/32
#   sudo scripts/cluster/restrict-kairon-relay.sh --remove
#
# Defaults: --port 22230 (pin the relay with kairon-node's --console-port so it does not move),
# loopback and the node's own address always allowed, plus --allow CIDRs (default 10.0.0.0/8,
# the Cilium pod range; use 10.42.0.0/16 for a flannel k3s cluster).
set -euo pipefail

PORT=22230
REMOVE=0
ALLOW=()
while [[ $# -gt 0 ]]; do
  case "$1" in
    --port) PORT="${2:?--port needs a value}"; shift 2 ;;
    --allow) ALLOW+=("${2:?--allow needs a CIDR}"); shift 2 ;;
    --remove) REMOVE=1; shift ;;
    -h|--help) sed -n '2,16p' "$0"; exit 0 ;;
    *) echo "unknown argument: $1" >&2; exit 2 ;;
  esac
done
[[ ${#ALLOW[@]} -gt 0 ]] || ALLOW=(10.0.0.0/8)
[[ "$PORT" =~ ^[0-9]+$ && "$PORT" -ge 1 && "$PORT" -le 65535 ]] || { echo "invalid port: $PORT" >&2; exit 2; }
for c in "${ALLOW[@]}"; do
  [[ "$c" =~ ^[0-9]{1,3}(\.[0-9]{1,3}){3}(/[0-9]{1,2})?$ ]] || { echo "invalid CIDR: $c" >&2; exit 2; }
done
[[ $EUID -eq 0 ]] || { echo "run as root" >&2; exit 1; }

SBIN=/usr/local/sbin/kairon-relay-firewall.sh
UNIT=/etc/systemd/system/kairon-relay-firewall.service

if [[ $REMOVE -eq 1 ]]; then
  systemctl disable --now kairon-relay-firewall.service 2>/dev/null || true
  for ipt in iptables ip6tables; do
    command -v "$ipt" >/dev/null || continue
    while "$ipt" -D INPUT -p tcp --dport "$PORT" -j KAIRON_RELAY 2>/dev/null; do :; done
    "$ipt" -F KAIRON_RELAY 2>/dev/null || true
    "$ipt" -X KAIRON_RELAY 2>/dev/null || true
  done
  rm -f "$SBIN" "$UNIT"; systemctl daemon-reload
  echo "relay port $PORT is open again"
  exit 0
fi

allow_rules=""
for c in "${ALLOW[@]}"; do allow_rules+="iptables -A KAIRON_RELAY -s $c -j RETURN"$'\n'; done

cat >"$SBIN" <<SCRIPT
#!/bin/sh
# Generated by restrict-kairon-relay.sh. Idempotent.
PORT=$PORT
SELF="\$(ip -4 route get 1.1.1.1 2>/dev/null | awk '{for(i=1;i<NF;i++) if(\$i=="src") print \$(i+1)}' | head -1)"
iptables -N KAIRON_RELAY 2>/dev/null || true
iptables -F KAIRON_RELAY
iptables -A KAIRON_RELAY -s 127.0.0.0/8 -j RETURN
${allow_rules}[ -n "\$SELF" ] && iptables -A KAIRON_RELAY -s "\$SELF/32" -j RETURN
iptables -A KAIRON_RELAY -j DROP
iptables -C INPUT -p tcp --dport "\$PORT" -j KAIRON_RELAY 2>/dev/null || iptables -I INPUT 1 -p tcp --dport "\$PORT" -j KAIRON_RELAY
if command -v ip6tables >/dev/null 2>&1; then
  ip6tables -N KAIRON_RELAY 2>/dev/null || true
  ip6tables -F KAIRON_RELAY
  ip6tables -A KAIRON_RELAY -s ::1/128 -j RETURN
  ip6tables -A KAIRON_RELAY -j DROP
  ip6tables -C INPUT -p tcp --dport "\$PORT" -j KAIRON_RELAY 2>/dev/null || ip6tables -I INPUT 1 -p tcp --dport "\$PORT" -j KAIRON_RELAY
fi
SCRIPT
chmod 0755 "$SBIN"

cat >"$UNIT" <<UNITFILE
[Unit]
Description=Restrict the kairon-node console relay port to local and in-cluster clients
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
RemainAfterExit=yes
ExecStart=$SBIN

[Install]
WantedBy=multi-user.target
UNITFILE

systemctl daemon-reload
systemctl enable --now kairon-relay-firewall.service
echo "relay port $PORT now accepts only: 127.0.0.0/8, this host, ${ALLOW[*]}"
iptables -S KAIRON_RELAY
